"""Generate docs/CALIBRATION.md from calibration/output/*.json so every number in the doc
matches the committed outputs exactly (no hand-typed results)."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
REG = ("Expansion", "Late-cycle", "Recession", "Recovery")


def pct(x: float, d: int = 1) -> str:
    return f"{100 * x:.{d}f}%"


def _band_row(name: str, b: dict, fmt) -> str:
    return f"| {name} | {fmt(b['median'])} | {fmt(b['p05'])} – {fmt(b['p95'])} | {b['mc_noise_ratio']:.2f} |"


def main() -> None:
    r = json.loads((ROOT / "calibration" / "output" / "report.json").read_text())
    man = json.loads((ROOT / "calibration" / "output" / "manifest.json").read_text())
    band_p = ROOT / "calibration" / "output" / "band_default.json"
    band = json.loads(band_p.read_text()) if band_p.exists() else None
    L = []
    w = L.append
    w("# Calibration (NL, step 2)\n")
    w("_Generated by `calibration/write_docs.py` from `calibration/output/report.json`. Do not edit by hand._\n")
    w(f"Calibrated {r['calibrated_utc']}. Estimation sample **{r['sample']}**. "
      "Regime labels need 24 months of indicator history; the euro-area unemployment series starts 2000-03, "
      "so the first labelled month is 2002-02 even though the agreed start is 1999.\n")
    w("**Read results as bands.** As agreed (option C), every outcome is reported as the median and the "
      "5th–95th percentile across 200 bootstrap re-calibrations, *for each of the two regime methods*. The "
      "full-sample files `params/nl_calibrated*.yaml` are only the bootstrap reference.\n")

    w("## 1. Data\n")
    w("| Series | Provider | Key | Retrieved (UTC) | SHA-256 (first 12) |\n|---|---|---|---|---|")
    for n, m in man.items():
        w(f"| {n} | {m['provider']} | `{m['key']}` | {m['retrieved_utc']} | `{m['sha256'][:12]}` |")
    w("\nURLs and full hashes: `calibration/output/manifest.json`. Raw files are cached locally in `data/cache/` "
      "and not committed, because provider licences differ. `python -m calibration.download --refresh` "
      "re-fetches them.\n")
    w("Transformations (all in `calibration/dataset.py`):")
    w("- **Short rate:** EONIA − 8.5 bp up to 2019-09 (the ECB's fixed EONIA–€STR spread), then €STR "
      "(monthly mean).")
    w("- **Term spread:** German 2-year zero-coupon yield (Bundesbank) − short rate.")
    w("- **Mortgage rate:** NL new loans, fixed > 10 years (ECB MIR, from 2003-01).")
    w("- **Inflation:** NL HICP year on year (Eurostat ECOICOP v2).")
    w("- **Equity:** developed-market total return (Kenneth French library) in USD, converted to EUR "
      "with the ECB USD/EUR reference rate.")
    w(f"- **House prices:** CBS 85773NED monthly log growth. Seasonality F-test p = "
      f"{r['house_seasonality']['p_value']:.1e}, so calendar-month means are removed.\n")

    w("## 2. Regimes: two methods\n")
    x = r["regime_cross_check"]
    w(f"- **Primary:** the agentic repo's threshold classifier, ported exactly and applied to euro-area "
      "indicators with publication lags (`calibration/classify.py`).")
    w(f"- **Cross-check:** a 4-state Gaussian hidden Markov model (HMM) on the four dimension scores, fitted "
      "by EM with 20 starts. States are named by maximum overlap with the primary labels.")
    w(f"- **Agreement:** the two methods give the same label in {pct(x['agreement'])} of months "
      f"(Cohen's κ = {x['cohens_kappa']:.2f}).\n")
    w("| | " + " | ".join(REG) + " |\n|---|" + "---|" * 4)
    for m, v in r["variants"].items():
        w(f"| months ({m}) | " + " | ".join(str(v["regime_months"][k]) for k in REG) + " |")
        w(f"| expected spell, months ({m}) | " + " | ".join(f"{v['expected_duration_months'][k]:.1f}" for k in REG) + " |")
        w(f"| long-run share ({m}) | " + " | ".join(pct(v["stationary_distribution"][k], 0) for k in REG) + " |")
        w(f"| probability today ({m}) | " + " | ".join(pct(v["initial_regime_probs"][k], 0) for k in REG) + " |")
    w("\nThe repo classifier labels each month on its own, with no memory, so its regimes switch every few "
      "months. The HMM's regimes persist for over a year. Results under both methods are shown "
      "side by side.\n")

    w("## 3. Estimates (full-sample reference; 5th / 50th / 95th bootstrap percentiles)\n")
    for m, v in r["variants"].items():
        rp = v["reference_params"]
        pp = v["bootstrap"]["param_percentiles"]
        w(f"### {m}\n")
        w("| Parameter | " + " | ".join(REG) + " |\n|---|" + "---|" * 4)
        for blk, fld, lab_ in (("equity", "mu", "Equity mean log return p.a."),
                               ("equity", "sigma", "Equity volatility p.a."),
                               ("house", "mu", "House-price growth p.a. (latent)"),
                               ("short_rate", "theta", "Short-rate regime level"),
                               ("mortgage_rate", "theta", "Mortgage-rate regime level"),
                               ("inflation", "theta", "Inflation regime level")):
            cells = []
            for i, k in enumerate(REG):
                q = pp[f"{blk}.{fld}"][k]
                cells.append(f"{pct(rp[blk][fld][i])} ({pct(q[0])} / {pct(q[1])} / {pct(q[2])})")
            w(f"| {lab_} | " + " | ".join(cells) + " |")
        w("")
        hs = v.get("house_state_space", {})
        w(f"- **House prices:** state-space MLE. Latent persistence φ = {rp['house']['ar1']:.3f} "
          f"(bootstrap {pp['house.ar1'][0]:.2f} / {pp['house.ar1'][1]:.2f} / {pp['house.ar1'][2]:.2f}); "
          f"index noise sd {hs.get('index_noise_sd_monthly', float('nan')) * 100:.2f}% per month.")
        for lv in ("short_rate", "term_spread", "mortgage_rate", "inflation"):
            q = pp[f"{lv}.half_life_months"]
            c = v["level_constraints"][lv]
            bind = [REG[i] for i, b in enumerate(c["theta_bound_binding"]) if b]
            w(f"- **{lv}:** half-life {rp[lv]['half_life_months']:.1f} months (bootstrap {q[0]:.0f} / {q[1]:.0f} / "
              f"{q[2]:.0f}); starts at {pct(rp[lv]['initial'], 2)}; regime level held to the sample range "
              f"[{pct(c['range'][0], 2)}, {pct(c['range'][1], 2)}] in: {', '.join(bind) or 'none'}.")
        sh = v["lw_shrinkage"]
        w("- **Correlation shrinkage (Ledoit-Wolf intensity, 1 = fully shrunk):** pooled→identity "
          f"{sh['_pooled_to_identity']:.2f}; " + ", ".join(f"{k}→pooled {sh[k]:.2f}" for k in REG if k in sh) + ".")
        b = v["bootstrap"]
        w(f"- **Bootstrap:** {b['replicates']} replicates; mean block {b['mean_block_length']:.1f} months "
          f"(Politis-White max over series: " + ", ".join(f"{k} {x:.1f}" for k, x in b["block_lengths"].items()) + ").")
        fb = {k: x for k, x in b["fallback_frequency"].items()}
        w(f"- **Replicates using any fallback or bound:** {pct(b['replicates_with_any_fallback'])}. Most frequent: " +
          (", ".join(f"{k} {pct(x, 0)}" for k, x in sorted(fb.items(), key=lambda kv: -kv[1])[:6]) or "none") + ".\n")
    iv = r["implied_vol"]
    w(f"**Implied volatility** (shared by both methods):")
    w(f"- Volatility premium ratio {iv['vrp_ratio']:.3f}: VIX vs next-month US realised variance, "
      f"{iv['_detail']['months_vrp']} months.")
    w(f"- Skew slope {iv['skew']:.3f} per unit of −ln(K/S): mean Cboe SKEW "
      f"{iv['_detail']['skew_index_mean']:.1f}, so 30-day risk-neutral skewness is "
      f"{iv['_detail']['gamma_30d']:.2f}, scaled to 1 year as {iv['_detail']['gamma_1y']:.2f}, converted "
      "with Backus, Foresi & Wu (2004).")
    w(f"- Volatility floor {pct(iv['min_vol'])}: the lowest VIX on record.\n")

    w("## 4. Validation (in-sample)\n")
    w("**One-month forecast checks (PIT).** If the model is right, about 10% of months should fall outside "
      "the 90% interval and about 2% outside the 98% interval.\n")
    w("| Variable | method | n | KS p | outside 90% | outside 98% |\n|---|---|---|---|---|---|")
    for m, v in r["variants"].items():
        for k, s in v["validation"]["one_step_pit"].items():
            w(f"| {k} | {m} | {s['n']} | {s['ks_p']:.3f} | {pct(s['outside_90pct'])} | {pct(s['outside_98pct'])} |")
    w("\n**10-year windows** (every 6 months, so the windows overlap heavily; descriptive only). Each "
      "simulation starts from the observed state, and the table shows how often the realised outcome "
      "fell inside the model's 5–95% range (nominal 90%).\n")
    w("| Outcome | method | windows | inside 5–95% | mean percentile of outcome |\n|---|---|---|---|---|")
    for m, v in r["variants"].items():
        for k, s in v["validation"]["ten_year_coverage"].items():
            w(f"| {k} | {m} | {s['windows']} | {pct(s['share_inside_5_95'])} | {s['mean_percentile_of_outcome']:.2f} |")
    w("")

    w("## 5. Historical episodes (data-derived scenarios)\n")
    w("| Episode | window (found by rule) | months | equity | house | short rate | mortgage | inflation |"
      "\n|---|---|---|---|---|---|---|---|")
    for e in r["scenarios"]["repo_classifier"]:
        o = e["observed_change"]
        f = lambda v, lg=False: "n/a" if v is None else (pct(np.expm1(v)) if lg else f"{v * 1e4:+.0f} bp")  # noqa: E731
        w(f"| {e['name']} | {e['window'][0]} → {e['window'][1]} | {e['duration_months']} | {f(o['equity_log'], True)} | "
          f"{f(o['house_log'], True)} | {f(o['short_rate'])} | {f(o['mortgage_rate'])} | {f(o['inflation'])} |")
    w("\nThe stored shocks are the part of each move *not* explained by the model's expected path along "
      "the episode's own regime sequence, so replaying an episode reproduces the historical move in "
      "expectation. See `params/nl_scenarios.json`.\n")

    if band:
        w("## 6. Illustration: default saver and glidepath, as bands\n")
        w(f"Saver: {band['saver']}. Glidepath: the agreed step table. {band['n_paths']} paths per replicate, "
          "identical random draws across replicates.\n")
        w("The MC noise ratio is within-replicate simulation noise divided by the band's half-width. "
          "Below 0.25, the band reflects parameter uncertainty rather than too few paths.\n")
        for m, b in band["bands"].items():
            w(f"### {m}\n")
            w("| Outcome | median | 5–95% band across re-calibrations | MC noise ratio |\n|---|---|---|---|")
            for k, lab_ in (("p_reach_deposit", "P(reach deposit)"), ("p_outpace_cash", "P(outpace cash)"),
                            ("p_keep_up_with_housing", "P(keep up with housing)"), ("p_all_three", "P(all three)")):
                w(_band_row(lab_, b[k], pct))
            eur = lambda v: f"€{v:,.0f}"                                       # noqa: E731
            w(_band_row("Median pot at purchase", b["pot_nominal.p50"], eur))
            w(_band_row("Median required deposit", b["required_deposit.p50"], eur))
            d = b["p_reach_deposit"]["drivers_spearman"]
            w("\nMain drivers of P(reach deposit) across re-calibrations (Spearman rank correlation): " +
              ", ".join(f"{k} {v:+.2f}" for k, v in list(d.items())[:4]) + ".\n")
    (ROOT / "docs" / "CALIBRATION.md").write_text("\n".join(L) + "\n")
    print("docs/CALIBRATION.md written")


if __name__ == "__main__":
    main()
